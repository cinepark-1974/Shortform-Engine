#  DOCUMENT IMPORT — 문서에서 컨셉 입력칸 채우기 (v2.5)
#  기획서·시놉시스·트리트먼트를 읽어 입력칸에 나눠 담고,
#  문서에 없는 칸은 문서와 어긋나지 않게 지어 채운다.
