    ex = get_formula_examples(formula_key)
    if lead == "male" and tone == "harsh":
        male = ex.get("male") or FORMULA_EXAMPLES["_공통"]["male"]
        return male["evil"], male["scene"]
    return ex["evil"][tone], ex["scene"][tone]


